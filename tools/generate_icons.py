"""Convert bundled PNGs into LVGL 9 ARGB8888 assets. Run before committing changes.

Requires Pillow on the development PC only; firmware builds need no image converter.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
SIZE = 96
CATALOGUE = (
    ('bambu_lab', 'bambu-lab.png'),
    ('lyra', 'lyra.png'),
    ('terminal', 'terminal.png'),
    ('vivaldi', 'vivaldi.png'),
    ('solidcraft', 'SolidCraft_logo.png'),
    ('sublime_text', 'sublime-text.png'),
)


def render():
    lines = ['// Generated by tools/generate_icons.py; do not edit.',
             '#include "embedded_icons.h"', '#include <cstring>',
             'namespace esphome::desktop_launcher::embedded_icons {', 'namespace {']
    for key, filename in CATALOGUE:
        with Image.open(ROOT / 'assets/icons' / filename) as source:
            image = ImageOps.contain(source.convert('RGBA'), (SIZE, SIZE), Image.Resampling.LANCZOS)
            canvas = Image.new('RGBA', (SIZE, SIZE))
            canvas.paste(image, ((SIZE-image.width)//2, (SIZE-image.height)//2))
        # LVGL ARGB8888 on little-endian ESP32: bytes B, G, R, A.
        data = canvas.tobytes('raw', 'BGRA')
        lines += [f'alignas(4) static const uint8_t {key}_pixels[] = {{']
        for offset in range(0, len(data), 32):
            lines.append('  ' + ','.join(f'0x{x:02x}' for x in data[offset:offset+32]) + ',')
        lines += ['};', f'static const lv_image_dsc_t {key}_image = [] {{',
                  '  lv_image_dsc_t d{};', '  d.header.magic = LV_IMAGE_HEADER_MAGIC;',
                  '  d.header.cf = LV_COLOR_FORMAT_ARGB8888;',
                  f'  d.header.w = {SIZE};', f'  d.header.h = {SIZE};', f'  d.header.stride = {SIZE * 4};',
                  f'  d.data_size = sizeof({key}_pixels);', f'  d.data = {key}_pixels;',
                  '  return d;', '}();']
    lines += ['}  // namespace', 'const lv_image_dsc_t *find(const std::string &path) {']
    for key, filename in CATALOGUE:
        lines.append(f'  if (path == "/local/Icons/{filename}" || path == "{filename}") return &{key}_image;')
    lines += ['  return nullptr;', '}', '}  // namespace esphome::desktop_launcher::embedded_icons', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'components/desktop_launcher/embedded_icons.cpp'
    content = render()
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit('Embedded icons stale: run python tools/generate_icons.py')
        print('Embedded icons are up to date')
    else:
        target.write_text(content)
        print(f'Generated {len(CATALOGUE)} icons, {len(CATALOGUE)*SIZE*SIZE*4} bytes of pixel data')
